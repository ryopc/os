; ===========================================================================
; boot.asm - x86_64 ブートエントリ (Limine プロトコル)
;
; モード遷移の責務範囲:
;   Limine はファームウェア (BIOS / UEFI) の 16 ビットモードから自前の
;   ステージで 32 ビットプロテクトモードを経て 64 ビット long mode へ遷移し、
;   ページングと GDT を設定したうえでこの boot_entry へジャンプする。
;   したがって本ファイルは 16/32 ビットのセットアップを持たず、
;     1. long mode で動作していることの検証 (fail fast)
;     2. カーネル専用スタックの用意
;     3. C 側エントリ (_start) への制御受け渡し
;   のみを担当する。
;
;   ELF のエントリポイントはリンカスクリプトの ENTRY(boot_entry) で指定する。
; ===========================================================================

bits 64

; ---------------------------------------------------------------------------
; Limine ベースリビジョンタグ
;
; Limine はこのタグでカーネルのプロトコル版を判定する。タグが無い、または
; ブートローダ側の対応版より新しい場合はブートを拒否するため、
; .limine_requests セクションに必ず配置する (リンカスクリプトで KEEP)。
; ---------------------------------------------------------------------------
section .limine_requests progbits alloc noexec nowrite align=8
global limine_base_revision
limine_base_revision:
    dq 0xf9562b2d5c95a6c8           ; ベースリビジョンタグ識別子 (前半)
    dq 0x6a7b384944536369           ; ベースリビジョンタグ識別子 (後半)
    dq 3                            ; カーネルが準拠するベースリビジョン

; ---------------------------------------------------------------------------
; エントリポイント
; ---------------------------------------------------------------------------
section .text
global boot_entry
extern _start                       ; kernel.c の C エントリポイント

boot_entry:
    cli                             ; 割り込みはカーネルが初期化するまで禁止
    cld                             ; 文字列命令は前方参照に固定

    ; IA32_EFER.LMA (bit 8) を読み、long mode でなければ起動失敗として停止する。
    ; Limine 経由なら必ずセットされているため、ここで落ちる場合は
    ; 「Limine 以外の経路でロードされた」ことを意味する。
    mov ecx, 0xC0000080             ; IA32_EFER
    rdmsr
    test eax, 0x100                 ; LMA ビット
    jz boot_failed

    ; Limine から渡されるスタックは保証されないため、自前のスタックへ切り替える。
    mov rsp, stack_top
    xor ebp, ebp                    ; フレームポインタを終端させる

    ; rdi には Limine のブート情報ポインタが渡される場合がある。
    ; 現状のカーネルは未使用だが、呼び出し規約の第一引数としてそのまま引き渡す。
    call _start

.halt:
    cli
    hlt
    jmp .halt

; 起動前提が崩れていた場合の最終手段。VGA テキストバッファの先頭に
; 赤地の '!' を書いてから停止する (シリアル未初期化でも視認できる)。
boot_failed:
    mov rdx, 0xB8000                ; 書き込み先 (VGA テキスト先頭)
    mov ax, 0x4F21                  ; 属性 0x4F (赤地に白) + '!'
    mov [rdx], ax                   ; ax がアドレスを壊さないよう rdx を base に使う
.hang:
    cli
    hlt
    jmp .hang

; ---------------------------------------------------------------------------
; カーネルスタック (16 KiB)
; ---------------------------------------------------------------------------
section .bss
alignb 16
stack_bottom:
    resb 16384
stack_top:
